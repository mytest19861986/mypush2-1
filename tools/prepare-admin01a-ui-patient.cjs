const fs = require('node:fs')
const { randomBytes } = require('node:crypto')
const { PrismaClient } = require('/runtime/node_modules/@prisma/client')
const { hash } = require('/runtime/node_modules/bcryptjs')
if (process.env.DATABASE_URL !== 'file:/data/admin01a-ui.sqlite') throw Error('Only the isolated UI fixture is permitted')
if (fs.existsSync('/data/patient-login.json')) throw Error('Existing test credentials must be preserved')
const db = new PrismaClient({ log: [] })
;(async () => {
  const user = await db.user.findUniqueOrThrow({ where: { id: 'codex01b-patient' }, include: { roles: { include: { role: true } } } })
  if (!user.roles.some(link => link.role.name === 'USER') || user.roles.some(link => ['ADMIN', 'SUPER_ADMIN'].includes(link.role.name))) throw Error('Unexpected synthetic account roles')
  const password = randomBytes(24).toString('base64url')
  await db.user.update({ where: { id: user.id }, data: { passwordHash: await hash(password, 12), isPasswordLoginEnabled: true, isMobileVerified: true, status: 'ACTIVE', failedLoginAttempts: 0, lockedUntil: null } })
  fs.writeFileSync('/data/patient-login.json', JSON.stringify({ origin: 'http://127.0.0.1:3323', mobile: user.mobile, password }), { mode: 0o600 })
  console.log(JSON.stringify({ syntheticPatientReady: true, valuesOmitted: true }))
})().catch(error => { console.error(error.name); process.exitCode = 1 }).finally(() => db.$disconnect())
